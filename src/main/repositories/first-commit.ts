import { promises as fs } from 'node:fs'
import { join } from 'node:path'
import type { AppError } from '../../shared/domain/errors'
import { makeAppError } from '../../shared/domain/errors'
import type { ExecutionTarget, RepositoryRecord } from '../../shared/domain/repository'
import type { GitWorktreeService } from '../worktrees/git-worktree-service'
import type { GuestGitResult } from '../wsl/git/guest-git'
import type { WslCommandRunner, WslExecOutcome } from '../wsl/exec'
import { isTransportOutcome } from '../wsl/probe'

/**
 * The first commit is allowed to take minutes, but it must never block a
 * dialog. These budgets are therefore deliberately larger than the old 60s
 * synchronous guard; progress is reported by the project card instead.
 */
const STAGE_TIMEOUT_MS = 5 * 60_000
const COMMIT_TIMEOUT_MS = 5 * 60_000
const PROBE_TIMEOUT_MS = 20_000
const FIRST_COMMIT_MESSAGE = 'Initial commit'

/**
 * Dependency and cache directories that must not be walked by `git add`.
 *
 * The list is deliberately conservative: it contains directories that are
 * generated by package managers, build caches and virtual environments. Build
 * outputs such as `dist/` and `build/` are not included because some projects
 * intentionally commit them; the user can extend `.gitignore` later.
 */
export const GENERATED_IGNORE_PATTERNS = [
  'node_modules/',
  '.venv/',
  'venv/',
  '__pycache__/',
  '.pytest_cache/',
  '.mypy_cache/',
  '.ruff_cache/',
  '.tox/',
  '.nox/',
  '.next/',
  '.nuxt/',
  '.svelte-kit/',
  '.turbo/',
  '.cache/',
  '.parcel-cache/',
  '.gradle/'
] as const

export type FirstCommitResult = {
  /** The repository already had a commit when preparation started. */
  alreadyCommitted: boolean
  committedFiles: number
  skippedFolders: string[]
  branch: string | null
  /** True when iCode created a .gitignore and included it in the commit. */
  createdGitignore: boolean
}

export class RepositoryPreparationError extends Error {
  constructor(readonly appError: AppError) {
    super(appError.message)
    this.name = 'RepositoryPreparationError'
  }
}

export type FirstCommitDeps = {
  runner: WslCommandRunner
  gitWorktrees: Pick<GitWorktreeService, 'gitResultFor'>
  /** Checked before the history-changing commit; used when a project is removed. */
  isCancelled?: () => boolean
}

type GitRunner = (
  cwd: string,
  args: string[],
  timeoutMs?: number
) => Promise<GuestGitResult>

/**
 * Creates the baseline commit for a repository that has no HEAD.
 *
 * This runs outside the Add-project request. Its only job is the expensive and
 * failure-prone part: reading the identity, leaving dependency/cache folders
 * out, staging and committing. Registration already happened, so a failure
 * leaves a real project with a retryable preparation error rather than a
 * half-registered UI row.
 */
export async function prepareFirstCommit(
  repository: RepositoryRecord,
  deps: FirstCommitDeps
): Promise<FirstCommitResult> {
  const target = repository.executionTarget
  const git = await deps.gitWorktrees.gitResultFor(target)
  const root = repository.path
  const branch = await readBranch(git, root)

  const head = await runGit(git, root, ['rev-parse', '--verify', 'HEAD'], PROBE_TIMEOUT_MS)
  if (head.timedOut) {
    throw new RepositoryPreparationError(
      makeAppError('GIT_READ_TIMEOUT', 'Git did not answer while checking the first commit.', {
        detail: 'The repository may be locked or the filesystem may be slow.',
        context: { path: root }
      })
    )
  }
  if (head.exitCode === 0) {
    return {
      alreadyCommitted: true,
      committedFiles: 0,
      skippedFolders: [],
      branch,
      createdGitignore: false
    }
  }

  const identity = await readIdentity(git, root)
  if (!identity.configured) {
    throw new RepositoryPreparationError(
      makeAppError('GIT_IDENTITY_MISSING', 'Git needs an author name and email before iCode can create the first commit.', {
        detail: 'Set user.name and user.email in Git, or add the project again with an identity.',
        context: { path: root }
      })
    )
  }

  const hasGitignore = await fileExists(joinForTarget(root, '.gitignore'), target, deps.runner)
  const empty = await directoryIsEmpty(root, target, deps.runner)
  const skippedFolders = hasGitignore || !empty ? [...GENERATED_IGNORE_PATTERNS] : []
  let createdGitignore = false

  /*
   * A new repository should not leave thousands of dependency files as
   * untracked noise. When the folder already owns a .gitignore, respect it and
   * use one-time pathspec excludes for this commit instead of rewriting the
   * user's file. Either way, Git never walks node_modules.
   */
  if (!hasGitignore && !empty) {
    await writeGitignore(root, target, deps.runner)
    createdGitignore = true
  }

  const addArgs = ['add', '-A', '--', '.']
  if (hasGitignore) {
    for (const pattern of GENERATED_IGNORE_PATTERNS) {
      addArgs.push(`:(exclude,glob)**/${pattern}**`)
    }
  }

  await runGitOrThrow(
    git,
    root,
    addArgs,
    STAGE_TIMEOUT_MS,
    'GIT_COMMIT_FAILED',
    'Could not stage the folder for its first commit.'
  )

  const staged = await runGitOrThrow(
    git,
    root,
    ['diff', '--cached', '--name-only'],
    PROBE_TIMEOUT_MS,
    'GIT_COMMIT_FAILED',
    'Git did not answer while preparing the first commit.'
  )
  const committedFiles = staged.stdout
    .toString('utf8')
    .split('\n')
    .filter((line) => line.trim().length > 0).length

  if (deps.isCancelled?.() === true) {
    throw new RepositoryPreparationError(
      makeAppError('GIT_COMMIT_FAILED', 'First-commit preparation was cancelled.', {
        detail: 'The project was removed before the commit was created.',
        context: { path: root }
      })
    )
  }

  await runGitOrThrow(
    git,
    root,
    ['commit', '--allow-empty', '-m', FIRST_COMMIT_MESSAGE],
    COMMIT_TIMEOUT_MS,
    'GIT_COMMIT_FAILED',
    'Git could not create the initial commit.'
  )

  return {
    alreadyCommitted: false,
    committedFiles,
    skippedFolders,
    branch: await readBranch(git, root),
    createdGitignore
  }
}

function joinForTarget(root: string, name: string): string {
  // `node:path` is the controller's path implementation; guest paths must stay
  // POSIX even when the Electron main process runs on Windows.
  return root.endsWith('/') ? `${root}${name}` : `${root}/${name}`
}

async function runGit(
  git: GitRunner,
  cwd: string,
  args: string[],
  timeoutMs: number
): Promise<GuestGitResult> {
  try {
    return await git(cwd, args, timeoutMs)
  } catch (error) {
    throw new RepositoryPreparationError(
      makeAppError('GIT_COMMIT_FAILED', 'Git could not be started for the first commit.', {
        detail: error instanceof Error ? error.message : String(error),
        context: { path: cwd }
      })
    )
  }
}

async function runGitOrThrow(
  git: GitRunner,
  cwd: string,
  args: string[],
  timeoutMs: number,
  code: 'GIT_COMMIT_FAILED' | 'GIT_READ_TIMEOUT',
  message: string
): Promise<GuestGitResult> {
  const result = await runGit(git, cwd, args, timeoutMs)
  if (result.timedOut) {
    throw new RepositoryPreparationError(
      makeAppError(code, message, {
        detail: `Git timed out after ${String(Math.round(timeoutMs / 1000))} seconds.`,
        context: { path: cwd }
      })
    )
  }
  if (result.spawnFailure !== undefined || result.exitCode !== 0) {
    const detail = result.stderr.toString('utf8').trim()
    throw new RepositoryPreparationError(
      makeAppError(code, message, {
        detail: detail.length > 0 ? detail.slice(0, 500) : 'Git exited with a failure.',
        context: { path: cwd }
      })
    )
  }
  return result
}

async function readIdentity(
  git: GitRunner,
  cwd: string
): Promise<{ configured: boolean }> {
  const [name, email] = await Promise.all([
    readConfig(git, cwd, 'user.name'),
    readConfig(git, cwd, 'user.email')
  ])
  return { configured: name !== null && email !== null }
}

async function readConfig(git: GitRunner, cwd: string, key: string): Promise<string | null> {
  const result = await runGit(git, cwd, ['config', '--get', key], PROBE_TIMEOUT_MS)
  if (result.timedOut || result.spawnFailure !== undefined || result.exitCode !== 0) return null
  const value = result.stdout.toString('utf8').trim()
  return value.length > 0 ? value : null
}

async function readBranch(git: GitRunner, cwd: string): Promise<string | null> {
  const result = await runGit(git, cwd, ['rev-parse', '--abbrev-ref', 'HEAD'], PROBE_TIMEOUT_MS)
  if (result.timedOut || result.spawnFailure !== undefined || result.exitCode !== 0) return null
  const branch = result.stdout.toString('utf8').trim()
  return branch.length > 0 && branch !== 'HEAD' ? branch : null
}

async function fileExists(
  path: string,
  target: ExecutionTarget,
  runner: WslCommandRunner
): Promise<boolean> {
  if (target.kind === 'local') {
    try {
      const info = await fs.stat(path)
      return info.isFile()
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code === 'ENOENT') return false
      throw new RepositoryPreparationError(
        makeAppError('GIT_COMMIT_FAILED', 'The folder could not be checked for .gitignore.', {
          detail: error instanceof Error ? error.message : String(error),
          context: { path }
        })
      )
    }
  }
  const result = await runGuestScript(
    runner,
    target.distro,
    'if [ -f "$1" ]; then printf yes; fi',
    'icode-ignore-check',
    path
  )
  return result.stdout === 'yes'
}

async function directoryIsEmpty(
  root: string,
  target: ExecutionTarget,
  runner: WslCommandRunner
): Promise<boolean> {
  if (target.kind === 'local') {
    try {
      const entries = await fs.readdir(root, { withFileTypes: true })
      return entries.every((entry) => entry.name === '.git')
    } catch (error) {
      throw new RepositoryPreparationError(
        makeAppError('GIT_COMMIT_FAILED', 'The folder could not be read for its first commit.', {
          detail: error instanceof Error ? error.message : String(error),
          context: { path: root }
        })
      )
    }
  }
  const result = await runGuestScript(
    runner,
    target.distro,
    'find "$1" -mindepth 1 -maxdepth 1 ! -name .git -print -quit',
    'icode-empty-check',
    root
  )
  return result.stdout.trim().length === 0
}

async function writeGitignore(
  root: string,
  target: ExecutionTarget,
  runner: WslCommandRunner
): Promise<void> {
  const content =
    '# Dependency and cache directories. iCode created this with the first commit.\n' +
    `${GENERATED_IGNORE_PATTERNS.join('\n')}\n`
  const path = joinForTarget(root, '.gitignore')
  if (target.kind === 'local') {
    try {
      await fs.writeFile(join(root, '.gitignore'), content, { encoding: 'utf8', flag: 'wx' })
    } catch (error) {
      // A concurrent writer winning the race is not a failure: the file exists,
      // and Git will use it for this commit.
      if ((error as NodeJS.ErrnoException).code !== 'EEXIST') {
        throw new RepositoryPreparationError(
          makeAppError('GIT_COMMIT_FAILED', 'iCode could not create a .gitignore for the first commit.', {
            detail: error instanceof Error ? error.message : String(error),
            context: { path }
          })
        )
      }
    }
    return
  }
  await runGuestScript(
    runner,
    target.distro,
    [
      'tmp="$1.icode-tmp-$$"',
      'trap \'rm -f -- "$tmp"\' 0 1 2 15',
      'cat > "$tmp" || exit 1',
      'mv -f -- "$tmp" "$1" || exit 1',
      'trap - 0 1 2 15'
    ].join('\n'),
    'icode-ignore-write',
    path,
    content
  )
}

async function runGuestScript(
  runner: WslCommandRunner,
  distro: string,
  script: string,
  name: string,
  path: string,
  stdin?: string
): Promise<{ stdout: string; stderr: string }> {
  let outcome: WslExecOutcome
  try {
    outcome = await runner.run({
      scope: 'guest',
      distro,
      argv: ['sh', '-c', script, name, path],
      ...(stdin === undefined ? {} : { stdin }),
      timeoutMs: PROBE_TIMEOUT_MS
    })
  } catch (error) {
    throw new RepositoryPreparationError(
      makeAppError('GIT_COMMIT_FAILED', 'The WSL distro did not answer while preparing the first commit.', {
        detail: error instanceof Error ? error.message : String(error),
        context: { path }
      })
    )
  }
  if (outcome.status !== 'ok') {
    const detail =
      outcome.status === 'exit_failure' ? outcome.stderr.trim() : isTransportOutcome(outcome) ? 'The WSL distro did not answer.' : ''
    throw new RepositoryPreparationError(
      makeAppError('GIT_COMMIT_FAILED', 'The folder could not be prepared for its first commit.', {
        detail: detail.length > 0 ? detail.slice(0, 500) : 'The WSL command did not complete.',
        context: { path }
      })
    )
  }
  return { stdout: outcome.stdout, stderr: outcome.stderr }
}
